            syntaxTrees: [CSharpSyntaxTree.ParseText(csharpSource, parseOptions)],
            references: SymbolTests.CreateAvaloniaReferences(),
            options: new CSharpCompilationOptions(
                OutputKind.DynamicallyLinkedLibrary,
                nullableContextOptions: NullableContextOptions.Enable));

        var catalog = AkburaGenerationCatalogBuilder.Create(
            compilation,
            [syntaxTree],
            "Demo",
            projectDirectory);

        var input = Assert.Single(catalog.ExternalAkcssModules);
        var generatedText = AkcssDocumentWriter.Generate(input, catalog.AkcssSourceMap, catalog.RootNamespace);

        AssertCompiles(
            catalog.Compilation.CSharpCompilation,
            (generatedText, AkcssDocumentWriter.GetHintName(input)));

        var generatedTree = CSharpSyntaxTree.ParseText(generatedText, parseOptions);
        var import = Assert.Single(
            generatedTree.GetCompilationUnitRoot().Usings,
            static directive => directive.Name?.ToString() == "Avalonia.Controls");

        Assert.Equal("using Avalonia.Controls;", import.ToString());
    }

    private static void AssertCompiles(
        CSharpCompilation compilation,
        params (SourceText Source, string Path)[] documents)
    {
        var parseOptions = CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.Preview);
        var syntaxTrees = new SyntaxTree[documents.Length];

        for (var i = 0; i < documents.Length; i++)
        {
            syntaxTrees[i] = CSharpSyntaxTree.ParseText(
                documents[i].Source,
                parseOptions,
                documents[i].Path);
        }

        var diagnostics = compilation
            .AddSyntaxTrees(syntaxTrees)
            .GetDiagnostics()
            .Where(static diagnostic =>
                diagnostic.Severity is DiagnosticSeverity.Warning or DiagnosticSeverity.Error)
            .ToArray();

        var generatedSource = string.Join(
            Environment.NewLine + Environment.NewLine,
            documents.Select(static document => document.Source.ToString()));

        Assert.True(
            diagnostics.Length == 0,
            string.Join(Environment.NewLine, diagnostics.Select(static diagnostic => diagnostic.ToString())) +
            Environment.NewLine +
            generatedSource);
    }

