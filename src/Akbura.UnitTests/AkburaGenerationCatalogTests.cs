    [Fact]
    public void DocumentWriter_PreservesDeclarationOrderAndUsesInterceptorRuntimeType()
    {
        const string akcssSource =
            """
            @using Avalonia.Controls;

            Border.before {
                Height: 10;
            }

            @utilities {
                Border.middle-(double value) {
                    Width: value;
                }
            }

            Border.after {
                Opacity: 0.5;
            }

            Border.intercepted {
                @intercept Demo.InterceptedStyle;
            }
            """;

        const string csharpSource =
            """
            namespace Demo;

            public sealed class InterceptedStyle : global::Akbura.Akcss.AkcssClass
            {
                public override void Update(object target)
                {
                }
            }
            """;

        var projectDirectory = Path.Combine(Path.GetTempPath(), "AkburaGenerationCatalogTests");
        var sourcePath = Path.Combine(projectDirectory, "Order.akcss");
        var parseOptions = CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.Preview);

        var syntaxTree = AkcssSyntaxTree.ParseText(
            SourceText.From(akcssSource),
            sourcePath,
            AkcssGeneratedModuleNames.GetMetadataName("Demo", "Order.akcss"));

        var compilation = CSharpCompilation.Create(
            "AkcssDeclarationOrderTests",
            syntaxTrees: [CSharpSyntaxTree.ParseText(csharpSource, parseOptions)],
            references: SymbolTests.CreateAvaloniaReferences(),
            options: new CSharpCompilationOptions(
                OutputKind.DynamicallyLinkedLibrary,
                nullableContextOptions: NullableContextOptions.Enable));

        var catalog = AkburaGenerationCatalogBuilder.Create(
            compilation,
            [syntaxTree],
            "Demo",
            projectDirectory);

        var input = Assert.Single(catalog.ExternalAkcssModules);
        var generatedText = AkcssDocumentWriter.Generate(input, catalog.AkcssSourceMap, catalog.RootNamespace);
        var generatedSource = generatedText.ToString();

        var before = generatedSource.IndexOf(
            "private sealed class Style_0 : global::Akbura.Akcss.AkcssClass",
            StringComparison.Ordinal);

        var middle = generatedSource.IndexOf(
            "private sealed class Style_1 : global::Akbura.Akcss.AkcssUtility<",
            StringComparison.Ordinal);

        var after = generatedSource.IndexOf(
            "private sealed class Style_2 : global::Akbura.Akcss.AkcssClass",
            StringComparison.Ordinal);

        Assert.True(before >= 0 && middle > before && after > middle, generatedSource);
        Assert.DoesNotContain("private sealed class Style_3", generatedSource, StringComparison.Ordinal);
        Assert.DoesNotContain("new Style_3()", generatedSource, StringComparison.Ordinal);
        Assert.Contains("new global::Demo.InterceptedStyle()", generatedSource, StringComparison.Ordinal);
        Assert.Contains("public static class __AkcssMetadata_3", generatedSource, StringComparison.Ordinal);

        AssertCompiles(
            catalog.Compilation.CSharpCompilation,
            (generatedText, AkcssDocumentWriter.GetHintName(input)));
    }

